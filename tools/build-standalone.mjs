// Builds orbit-standalone.html: the whole app in ONE file that also works when you
// double-click it (no server needed for the 3D view). Run:  npm run build
// 生成单文件版本 orbit-standalone.html，双击即可打开（AI 对话仍需服务器）。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = ['data', 'noise', 'textures', 'bodies', 'gestures', 'voice', 'chat', 'main'];

function convert(name, src) {
  const exported = [];
  let code = src
    .replace(/^import \* as T from 'three';\s*$/m, '')
    .replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+)\.js';\s*$/gm, (_, names, mod) =>
      `const { ${names.split(',').map(n => n.trim()).filter(Boolean).map(n => n.replace(/\s+as\s+/, ': ')).join(', ')} } = __m['${mod}'];`)
    .replace(/^export\s+(async\s+function|function|const|let|class)\s+([\w$]+)/gm, (_, kind, id) => { exported.push(id); return `${kind} ${id}`; });
  return `__m['${name}'] = (() => {\n${code}\nreturn { ${exported.join(', ')} };\n})();\n`;
}

const modules = ORDER.map(n => convert(n, fs.readFileSync(path.join(root, 'js', n + '.js'), 'utf8'))).join('\n');
const css = fs.readFileSync(path.join(root, 'css', 'style.css'), 'utf8');
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
html = html.replace('<link rel="stylesheet" href="css/style.css">', () => `<style>\n${css}\n</style>`);
html = html.replace('<script type="module" src="js/main.js"></script>', () =>
  `<script type="module">\n// Generated by tools/build-standalone.mjs from js/*.js. Edit the js/ files, then run npm run build.\nimport * as T from 'three';\nconst __m = {};\n${modules.replace(/<\/script/gi, '<\\/script')}</script>`);
fs.writeFileSync(path.join(root, 'orbit-standalone.html'), html);
console.log('Wrote orbit-standalone.html (' + Math.round(html.length / 1024) + ' KB)');
